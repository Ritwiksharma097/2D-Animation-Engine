"""Owner review page: background report preparation, all actions listed, a verdict saves and reloads.
Restores annotations/_reviews.json afterwards so the check leaves no fake review behind."""
import json, subprocess, sys, time
from pathlib import Path
from playwright.sync_api import sync_playwright
sys.path.insert(0, str(Path(__file__).resolve().parent))
from screenshot_workbench import ROOT, SHOTS, free_port, launch  # noqa: E402

REV = ROOT / "annotations" / "_reviews.json"


def main():
    before = REV.read_text(encoding="utf-8") if REV.exists() else None
    port = free_port()
    srv = subprocess.Popen([sys.executable, str(ROOT / "workbench/serve.py"), "--port", str(port)], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    time.sleep(1); fails = 0
    def check(name, ok, detail):
        nonlocal fails; fails += not ok; print(("PASS " if ok else "FAIL ") + name + ": " + detail)
    try:
        with sync_playwright() as p:
            br = launch(p); page = br.new_page(viewport={"width": 1300, "height": 1400})
            errs = []; page.on("pageerror", lambda e: errs.append(str(e)))
            page.goto(f"http://127.0.0.1:{port}/workbench/review.html"); page.wait_for_selector("body[data-ready='1']", timeout=60000)
            page.wait_for_function("document.querySelector('#prep').textContent.startsWith('reports ready')", timeout=180000)
            page.wait_for_timeout(1500); page.wait_for_selector("body[data-ready='1']")
            n = page.locator("section.card").count()
            man = json.loads((ROOT / "assets/manifest.json").read_text())
            total = sum(len(c["actions"]) for c in man["characters"].values())
            check("every action listed", n == total, f"{n} cards for {total} actions")
            check("missing reports were prepared", (ROOT / "out/guard/happy/report.json").exists() and (ROOT / "out/guard/idle/before_after.png").exists(),
                  "guard/happy report and guard/idle before_after regenerated by the server")
            idle = page.locator("section.card", has_text="guard/idle").first
            check("edited action shows before/after", idle.locator(".ba img").count() == 1 and "edited vs original" in idle.inner_text(), "guard/idle card")
            idle.locator("select.v").select_option("needs work"); idle.locator("textarea.cmt").fill("test comment from review_checks")
            idle.locator("button.save").click(); page.wait_for_timeout(800)
            saved = json.loads(REV.read_text())["reviews"].get("guard/idle", {})
            check("verdict saved", saved.get("verdict") == "needs work" and "test comment" in saved.get("comment", ""), str(saved))
            page.reload(); page.wait_for_selector("body[data-ready='1']", timeout=60000)
            v = page.locator("section.card", has_text="guard/idle").first.locator("select.v").input_value()
            check("verdict shown after reload", v == "needs work", v)
            page.screenshot(path=str(SHOTS / "40_review_top.png"))
            page.locator("section.card", has_text="guard/idle").first.scroll_into_view_if_needed(); page.wait_for_timeout(300)
            page.screenshot(path=str(SHOTS / "41_review_guard_idle.png"))
            check("no page errors", not errs, "; ".join(errs) or "none")
            br.close()
    finally:
        srv.terminate()
        if before is None:
            REV.unlink(missing_ok=True)
        else:
            REV.write_text(before, encoding="utf-8")
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
